from __future__ import annotations

import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from commitminer.classify import RULES, Category, Rule
from commitminer.cli import app
from commitminer.ruletable import classify_file, render_rules_markdown
from gitrepo import GitRepo, lines

runner = CliRunner()
ROOT = Path(__file__).resolve().parent.parent
SAMPLE = ROOT / "examples" / "classify"
SAMPLE_PATHS = [
    "src/lib.rs",
    "internal/kind/kind_string.go",
    "web/static/bundle.js",
    "web/src/app.test.ts",
    "vendor/github.com/acme/left/left.go",
    "fixtures/percent.json",
    "tools/cli/main.go",
    "Cargo.lock",
    "README.md",
]


def test_classify_the_sample_tree_golden() -> None:
    result = runner.invoke(app, ["classify", "--root", str(SAMPLE), *SAMPLE_PATHS])
    assert result.exit_code == 0, result.output
    table = result.stdout.split("\n\nrules used:\n")[0]
    assert table.splitlines() == [
        "category   rule               path",
        "source     rust-inline-tests  src/lib.rs  [rust-inline-tests]",
        "generated  generated-header   internal/kind/kind_string.go  [generated-header]",
        "generated  minified-content   web/static/bundle.js  [minified]",
        "test       js-test-file       web/src/app.test.ts",
        "vendored   vendored-dir       vendor/github.com/acme/left/left.go",
        "test       fixtures-dir       fixtures/percent.json",
        "source     go-source          tools/cli/main.go",
        "generated  lockfile           Cargo.lock *",
        "docs       docs-file          README.md",
        "* not a file under the root: classified by path only",
    ]
    assert "  fixtures-dir       this project keeps test inputs" in result.stdout


def test_classify_json_and_no_content() -> None:
    result = runner.invoke(
        app,
        ["classify", "--root", str(SAMPLE), "--json", "--no-content", "src/lib.rs", "x/y.bin"],
    )
    assert result.exit_code == 0, result.output
    first, second = (json.loads(line) for line in result.stdout.splitlines())
    assert first == {
        "category": "source",
        "content_read": False,
        "language": "rust",
        "path": "src/lib.rs",
        "rule": "rust-source",
        "signals": [],
    }
    assert second["rule"] == "fallback"
    assert second["language"] is None
    text = runner.invoke(app, ["classify", "--root", str(SAMPLE), "--no-content", "src/lib.rs"])
    assert "content not read (--no-content)" in text.stdout
    assert "rust-source" in text.stdout


