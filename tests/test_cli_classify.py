def test_classify_rejects_directories_and_outside_paths(tmp_path: Path) -> None:
    (tmp_path / "src").mkdir()
    result = runner.invoke(app, ["classify", "--root", str(tmp_path), "src"])
    assert result.exit_code == 2
    assert "src is a directory" in result.stderr
    outside = runner.invoke(app, ["classify", "--root", str(tmp_path / "src"), str(tmp_path)])
    assert outside.exit_code == 2
    assert "is outside the root" in outside.stderr


def test_classify_reports_config_errors(tmp_path: Path) -> None:
    (tmp_path / "commitminer.toml").write_text("[classify]\nbogus = 1\n", encoding="utf-8")
    result = runner.invoke(app, ["classify", "--root", str(tmp_path), "a.py"])
    assert result.exit_code == 2
    assert "unknown key 'bogus'" in result.stderr


def test_classify_file_reads_only_regular_files(tmp_path: Path) -> None:
    (tmp_path / "gen.go").write_bytes(b"// Code generated by x. DO NOT EDIT.\npackage p\n")
    verdict = classify_file(tmp_path, "gen.go", RULES)
    assert (verdict.rule_id, verdict.read, verdict.signals) == (
        "generated-header",
        True,
        ("generated-header",),
    )
    assert classify_file(tmp_path, "gen.go", RULES, content=False).rule_id == "go-source"
    assert classify_file(tmp_path, "nope.go", RULES).read is False


def test_rules_command_lists_the_effective_table() -> None:
    result = runner.invoke(app, ["rules", "--root", str(SAMPLE)])
    assert result.exit_code == 0, result.output
    out = result.stdout.splitlines()
    assert out[0] == (
        f"config: {SAMPLE / 'commitminer.toml'}: 1 custom rule, 1 built-in rule disabled"
    )
    assert out[1] == " 1. fixtures-dir -> test [any]  (commitminer.toml)"
    assert " 2. vendored-dir -> vendored [any]" in out
    assert not any("tooling-dir" in line for line in out)
    assert "    name: *Test.java, *Tests.java, *TestCase.java, *IT.java, " in result.stdout
    assert out[-1] == "    no rule matched -> other (fallback)"


