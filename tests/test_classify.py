@dataclass(frozen=True)
class Example:
    path: str
    category: Category
    rule_id: str
    content: str | None = None

    def classify(self) -> Classification:
        signals = detect_path(self.path, self.content.encode()) if self.content else ()
        return classify(self.path, signals=signals)


def ex(path: str, category: Category, rule_id: str, content: str | None = None) -> Example:
    return Example(path, category, rule_id, content)


