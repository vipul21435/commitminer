ALL_EXAMPLES = [
    pytest.param(example, id=f"{rule_id}:{'+' if positive else '-'}:{example.path}")
    for rule_id, (positives, negatives) in EXAMPLES.items()
    for positive, group in ((True, positives), (False, negatives))
    for example in group
]


@pytest.mark.parametrize("example", ALL_EXAMPLES)
def test_example_is_classified_as_expected(example: Example) -> None:
    assert example.classify() == Classification(example.category, example.rule_id)


def test_every_rule_has_examples() -> None:
    table_ids = [rule.rule_id for rule in RULES] + [FALLBACK_RULE]
    assert sorted(EXAMPLES) == sorted(table_ids)
    for rule_id, (positives, negatives) in EXAMPLES.items():
        assert positives, f"{rule_id} has no positive example"
        assert negatives, f"{rule_id} has no negative example"
        assert all(e.rule_id == rule_id for e in positives), rule_id
        assert all(e.rule_id != rule_id for e in negatives), rule_id


def test_positive_examples_carry_the_rule_category() -> None:
    by_id = {rule.rule_id: rule.category for rule in RULES}
    for rule_id, (positives, _) in EXAMPLES.items():
        for example in positives:
            assert example.category == by_id.get(rule_id, Category.OTHER), example


def test_rule_ids_are_unique() -> None:
    ids = [rule.rule_id for rule in RULES]
    assert len(ids) == len(set(ids))
    assert FALLBACK_RULE not in ids


def test_every_rule_is_reachable_and_has_a_rationale() -> None:
    for rule in RULES:
        assert rule.rationale.strip()
        assert rule.rationale.isascii()


def test_empty_table_falls_back() -> None:
    assert classify("tests/test_x.py", rules=()) == Classification(Category.OTHER, FALLBACK_RULE)
    assert match("tests/test_x.py", rules=()) is None


def test_match_returns_the_rule() -> None:
    rule = match("src/lib.rs", signals=["rust-inline-tests"])
    assert rule is not None
    assert rule.rule_id == "rust-inline-tests"
    assert rule.languages_label == "rust"
    first = match("vendor/x.go")
    assert first is not None
    assert first.languages_label == "any"


def test_signals_only_count_for_their_languages() -> None:
    # A signal attached to a file of another language does not trigger the rule.
    assert classify("src/app.py", signals=["minified"]).rule_id == "py-source"
    assert classify("src/app.js", signals=["minified"]).rule_id == "minified-content"


def test_target_normalises_paths() -> None:
    target = Target.of(".\\src/./pkg\\mod.py", ["x"])
    assert target.path == "src/./pkg/mod.py"
    assert target.parts == ("src", ".", "pkg", "mod.py")
    assert target.directories == ("src", ".", "pkg")
    assert target.name == "mod.py"
    assert target.signals == frozenset({"x"})
    assert Target.of("././a.go").path == "a.go"


